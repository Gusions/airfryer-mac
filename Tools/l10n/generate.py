"""Validates the translations and generates Resources/<language>.lproj/Localizable.strings.

Checks: number of strings, same placeholders (%lld, %@) in the same order, no empty string.
Usage: python3 Tools/l10n/generate.py
"""
import glob
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from keys import EXTRA_KEYS, KEYS  # noqa: E402
from lang_extra import EXTRA  # noqa: E402

PLACEHOLDER = re.compile(r"%(?:\d+\$)?(?:lld|@)")


def load():
    langs = {}
    for path in sorted([p for p in glob.glob(os.path.join(HERE, "lang_*.py")) if not p.endswith("lang_extra.py")]):
        spec = importlib.util.spec_from_file_location("m", path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        for code, values in getattr(mod, "T", {}).items():
            if code in langs:
                sys.exit(f"Duplicate language: {code}")
            langs[code] = values
    for code, values in langs.items():
        extra = EXTRA.get(code)
        if extra is None or len(extra) != len(EXTRA_KEYS):
            sys.exit(f"{code}: missing extra strings")
        langs[code] = values + extra
    return langs


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    langs = load()
    langs["en"] = list(KEYS)
    errors = []
    expected = [PLACEHOLDER.findall(k) for k in KEYS]
    for code, values in langs.items():
        if len(values) != len(KEYS):
            errors.append(f"{code}: {len(values)} strings instead of {len(KEYS)}")
            continue
        for i, (key, value) in enumerate(zip(KEYS, values)):
            if not value.strip():
                errors.append(f"{code}[{i}]: empty")
            found = [re.sub(r"\d+\$", "", p) for p in PLACEHOLDER.findall(value)]
            if found != expected[i]:
                errors.append(f"{code}[{i}] {key!r}: placeholders {found} instead of {expected[i]}")
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    for code, values in langs.items():
        folder = os.path.join(ROOT, "Resources", f"{code}.lproj")
        os.makedirs(folder, exist_ok=True)
        with open(os.path.join(folder, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("/* Generated by Tools/l10n/generate.py: do not edit by hand. */\n")
            for key, value in zip(KEYS, values):
                f.write(f'"{escape(key)}" = "{escape(value)}";\n')
    print(f"{len(langs)} languages, {len(KEYS)} strings each:", " ".join(sorted(langs)))


if __name__ == "__main__":
    main()
